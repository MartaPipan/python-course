# Створюємо порожній список, куди будемо збирати всі введені оцінки
scores = []

# Запускаємо нескінченний цикл для постійного введення даних
while True:
    # Запитуємо у користувача бал та обрізаємо випадкові пробіли по краях
    text = input("Бал або Enter для завершення: ").strip()
    
    # Перевіряємо умову виходу: якщо натиснули Enter, рядок `text` буде порожнім
    if not text:
        break  # Виходимо з циклу `while`
        
    # Перетворюємо введений текст на ціле число (наприклад, з "95" у 95)
    score = int(text)
    
    # Додаємо отримане число в кінець нашого списку scores
    scores.append(score)

# Перевіряємо, чи список не порожній (чи ввів користувач бодай одну оцінку)
if scores:
    # Рахуємо середнє арифметичне: суму всіх елементів ділимо на їх кількість
    average = sum(scores) / len(scores)
    
    # Виводимо середній бал, округлений до 1 знака після коми завдяки format-специфікатору :.1f
    print(f"Середній бал: {average:.1f}")
    
    # Знаходимо та виводимо найбільше число в списку за допомогою функції max()
    print("Найвищий:", max(scores))
else:
    # Цей блок спрацює, якщо користувач натиснув Enter на самому початку і список порожній
    print("Оцінок немає")



# Порожня множина —set().
# Операції  над  множинами    Підмножину перевіряють small<=big,    відсутність спільних елементів—isdisjoint().

lecture = {"Олена", "Марко", "Ірина"}
practice = {"Марко", "Ірина", "Тарас"}
print(lecture | practice) # об'єднання
print(lecture & practice) #перетин
print(lecture-practice) # лише на лекції
print(lecture ^ practice) # лише в одній множині