def percentage(part, whole):
    """Обчислює відсоток частини від цілого числа."""
    if whole == 0:
        return None
    return (part / whole) * 100

def double_value(number):
    """Проста функція, яка подвоює передане число."""
    return number * 2

def calculate_tax(price):
    """Формула: рахуємо 20% податку від ціни товару."""
    return price * 0.20

