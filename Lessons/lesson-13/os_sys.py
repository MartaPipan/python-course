# ==============================================================================
# ПРАКТИЧНИЙ ГІД: СТАНДАРТНІ МОДУЛІ 'sys' ТА 'os'
# Обидва модулі є частиною стандартної бібліотеки Python (їх не треба встановлювати через pip)
# ==============================================================================

import os
import sys

# ==============================================================================
# ЧАСТИНА 1: МОДУЛЬ 'sys' (Внутрішній світ інтерпретатора Python)
# Документація: https://python.org
# ==============================================================================
print("=" * 50)
print("1. ДОСЛІДЖЕННЯ МОДУЛЯ SYS")
print("=" * 50)

# sys.version -> Повертає рядок із поточною версією Python, яка зараз запущена
print(f"[*] Версія Python: {sys.version}")

# sys.platform -> Ідентифікує поточну операційну систему ('win32', 'linux', 'darwin' для Mac)
print(f"[*] Операційна платформа: {sys.platform}")

# sys.path -> Список рядків, який містить шляхи для пошуку модулів.
# Коли ви пишете 'import', Python шукає файли саме у цих папках.
print("\n[*] Перші 3 шляхи для пошуку у sys.path:")
for caminho in sys.path[:3]:
    print(f"  - {caminho}")

# sys.argv -> Список, який зберігає аргументи, передані в скрипт через командний рядок
# Індекс 0 — це завжди назва самого файлу, який зараз запускається.
print(f"\n[*] Аргументи командного рядка (sys.argv): {sys.argv}")
print(f"  - Назва цього файлу: {sys.argv[0]}")
if len(sys.argv) > 1:
    print(f"  - Переданий додатковий аргумент: {sys.argv[1]}")
else:
    print("  - Підказка: Запустіть у терміналі 'python estudo_sys_os.py test', щоб протестувати аргументи.")

print("\n" + "=" * 50)


# ==============================================================================
# ЧАСТИНА 2: МОДУЛЬ 'os' (Зовнішній світ, файли та операційна система)
# ==============================================================================
print("2. ДОСЛІДЖЕННЯ МОДУЛЯ OS")
print("=" * 50)

# os.getcwd() -> Отримує поточну робочу директорію (Current Working Directory)
diretorio_atual = os.getcwd()
print(f"[*] Поточна робоча папка: {diretorio_atual}")

# os.listdir() -> Показує список файлів і папок у вказаному шляху
print(f"\n[*] Список елементів у поточній папці (обмежено до 5):")
itens = os.listdir(".")  # Крапка '.' означає поточну директорію
for item in itens[:5]:
    print(f"  - {item}")

# ------------------------------------------------------------------------------
# 2.1 ПІДМОДУЛЬ: os.path (Розумна робота зі шляхами до файлів)
# ------------------------------------------------------------------------------
print("\n[*] Використання os.path для керування файлами:")

# os.path.join() -> Правильно зшиває частини шляху, автоматично додаючи потрібні косі риски
# (Запобігає конфліктам між зворотною рискою '\' у Windows та прямими '/' у Linux/Mac)
pasta_nova = "pasta_de_testes"
nome_arquivo = "meu_arquivo_teste.txt"
caminho_completo = os.path.join(diretorio_atual, pasta_nova, nome_arquivo)
print(f"  - Динамічно створений шлях: {caminho_completo}")

# os.path.exists() -> Перевіряє, чи існує папка або файл фізично на диску (Повертає True або False)
print(f"  - Чи існує папка '{pasta_nova}' зараз? {os.path.exists(pasta_nova)}")

# ------------------------------------------------------------------------------
# 2.2 ДИНАМІЧНЕ СТВОРЕННЯ ТА МАНІПУЛЯЦІЯ ДИРЕКТОРІЯМИ Й ФАЙЛАМИ
# ------------------------------------------------------------------------------
print("\n[*] Створення та очищення середовища за допомогою модуля 'os':")

if not os.path.exists(pasta_nova):
    # os.mkdir() -> Створює нову фізичну папку в системі
    os.mkdir(pasta_nova)
    print(f"  - Успіх: Папку '{pasta_nova}' створено!")
else:
    print(f"  - Попередження: Папка '{pasta_nova}' вже існувала.")

# Створюємо тимчасовий текстовий файл всередині нашої нової папки
caminho_arquivo = os.path.join(pasta_nova, nome_arquivo)
with open(caminho_arquivo, "w", encoding="utf-8") as f:
    f.write("Тестовий вміст, записаний за допомогою автоматизації Python через 'os'.")

# os.path.isfile() -> Перевіряє, чи є вказаний шлях саме файлом (а не папкою)
if os.path.isfile(caminho_arquivo):
    print(f"  - Файл успішно перевірено: {caminho_arquivo} (Розмір: {os.path.getsize(caminho_arquivo)} байт)")

# --- ОЧИЩЕННЯ ПІСЛЯ ТЕСТУВАННЯ ---
# os.remove() -> Видаляє файл із системи
os.remove(caminho_arquivo)
print("  - Тест завершено: Тимчасовий файл видалено.")

# os.rmdir() -> Видаляє порожню папку
os.rmdir(pasta_nova)
print("  - Тест завершено: Порожню папку очищено за допомогою os.rmdir().")

print("\n" + "=" * 50)
print("КІНЕЦЬ ТЕСТОВОГО СКРИПТА")
print("=" * 50)

# sys.exit() -> Чисто завершує роботу програми.
# Аргумент '0' означає, що програма виконалася успішно без критичних помилок.
sys.exit(0)
