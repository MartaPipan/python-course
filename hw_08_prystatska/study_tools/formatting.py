def format_report(label: str, value: float) -> str:
    """Приймає назву обчислення та число, повертає відформатований рядок звіту."""
    if value is None:
        return f"== Помилка обчислення для: {label} (отримано None) =="
    return f"--- РЕЗУЛЬТАТ [{label}] ---\nРозраховане значення: {value:.2f}\n---------------------------------"
